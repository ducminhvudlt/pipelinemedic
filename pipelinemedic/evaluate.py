"""Measure diagnosis quality on a labeled set of failures.

Each case has a log and the expected failure type, or null when the honest
answer is "I don't know" (escalate). Metrics:

- accuracy:          share of cases where the outcome matched the label
- false confidence:  of the cases where PipelineMedic named a cause, the share
                     where that cause was wrong (the number that matters most)
- escalation rate:   share of cases where it said "I don't know"
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

from .classifier import classify, load_taxonomy

DEFAULT_FIXTURES = Path(__file__).resolve().parent.parent / "fixtures" / "failures.json"


@dataclass
class CaseResult:
    id: str
    source: str
    expected: str | None
    predicted: str | None

    @property
    def correct(self) -> bool:
        return self.expected == self.predicted


@dataclass
class EvalResult:
    cases: list[CaseResult]

    @property
    def total(self) -> int:
        return len(self.cases)

    @property
    def accuracy(self) -> float:
        return sum(c.correct for c in self.cases) / self.total if self.total else 0.0

    @property
    def false_confidence(self) -> float:
        claimed = [c for c in self.cases if c.predicted is not None]
        return sum(not c.correct for c in claimed) / len(claimed) if claimed else 0.0

    @property
    def escalation_rate(self) -> float:
        return sum(c.predicted is None for c in self.cases) / self.total if self.total else 0.0

    def to_markdown(self) -> str:
        rows = "\n".join(
            f"| {c.id} | {c.source} | {c.expected or 'escalate'} | {c.predicted or 'escalate'} | "
            f"{'✅' if c.correct else '❌'} |"
            for c in self.cases
        )
        return (
            "# PipelineMedic evaluation\n\n"
            "Generated by `pipelinemedic eval --write EVAL.md`.\n\n"
            "> **Read this before the numbers.** The current set is **synthetic**: hand-written logs "
            "modeled on common dbt, Airflow, Spark and Postgres error messages, written alongside "
            "the taxonomy. A high score here shows the pipeline works end to end; it does **not** "
            "measure real-world accuracy. Results on real, anonymized production failures will be "
            "published here as they are collected, misses included.\n\n"
            f"| Metric | Value |\n|---|---|\n"
            f"| Cases | {self.total} |\n"
            f"| Accuracy | {self.accuracy:.0%} |\n"
            f"| False-confidence rate | {self.false_confidence:.0%} |\n"
            f"| Escalation rate | {self.escalation_rate:.0%} |\n\n"
            "| Case | Source | Expected | Predicted | |\n|---|---|---|---|---|\n"
            f"{rows}\n"
        )


def run_eval(fixtures_path: str | Path = DEFAULT_FIXTURES, taxonomy: dict | None = None) -> EvalResult:
    taxonomy = taxonomy or load_taxonomy()
    cases = json.loads(Path(fixtures_path).read_text(encoding="utf-8"))
    results = []
    for case in cases:
        predicted = classify(case["log"], taxonomy).failure_type
        results.append(CaseResult(case["id"], case.get("source", "?"), case["expected"], predicted))
    return EvalResult(results)
